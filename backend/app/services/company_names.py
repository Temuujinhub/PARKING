"""Гэрээт машины «Байгууллага» нэрийн цэвэрлэгээ + хог нэр таних.

Асуудал (2026-10-22, харилцагчийн №52): Excel импорт нь байгууллагын нэрийг
хуудасны нэр эсвэл гарчгийн мөрөөс авдаг тул продод ~2,670 бүртгэл «Улсын
дугаар», «дугаар», «Байгууллага 1», «data», «эзэмшигч», «Sheet1» гэх мэт
БАЙГУУЛЛАГА БИШ нэртэй орсон. Гараар бүртгэх цонхонд байгууллагын санал
(company-search) нэмэхэд эдгээр нь санал болгогдож шинэ бүртгэл рүү тархах
эрсдэлтэй тул энд нэг газар тодорхойлно:
  • company-search — хог нэрийг санал болгохгүй;
  • admin create/update — шинээр хог нэр оруулахыг хориглоно (гэрээт);
  • тайлан «Байгууллагаар» — мөрийг тэмдэглэнэ;
  • tools/company_junk_report.py — тоо/жагсаалт.
Өгөгдлийг ӨӨРЧЛӨХГҮЙ — зөвхөн таних функц.
"""
import re

# Хоосон/байгууллагагүй бүртгэлийн тайлангийн бүлэг (reports_router-тэй ижил)
NO_COMPANY = "(байгууллагагүй)"

# Жижиг үсэг, зай нэгтгэсэн, төгсгөлийн цэг/хоёр цэггүй хэлбэрээр харьцуулна.
# Excel-ийн гарчгийн нүд (driver_import.PLATE/NAME/NOTE/PHONE_HEADERS) + түгээмэл
# хуудасны нэр. «nissan» г.м жинхэнэ бүлгийн нэрийг энд ОРУУЛАХГҮЙ.
JUNK_COMPANY_NAMES = frozenset({
    "улсын дугаар", "дугаар", "машины дугаар", "plate", "plate number",
    "эзэмшигч", "нэр", "овог нэр", "owner", "name",
    "утас", "утасны дугаар", "phone",
    "албан тушаал", "тушаал", "position", "тэмдэглэл",
    "байгууллага", "байгууллагын нэр", "company", "компани",
    "data", "sheet", "лист", "хуудас", "жагсаалт", "д/д", "дд",
})
# «Sheet1», «Лист 2», «Хуудас3», «Байгууллага 1», «Page 4» — дугаарласан хуудасны нэр
_NUMBERED_RE = re.compile(r"^(?:sheet|лист|хуудас|page|байгууллага|company)\s*\d+$")
# Үсэггүй (зөвхөн тоо/тэмдэгт) нэр — «1», «-», «№ 3» г.м
_NO_LETTER_RE = re.compile(r"^[\W\d_]+$")


def normalize_company(raw) -> str:
    """Төгсгөлийн зай хасаж, дундах олон зайг нэг болгоно («  Голомт   банк » →
    «Голомт банк»). Тайлан нэрээр бүлэглэдэг тул зайн зөрүү өөр байгууллага
    мэт харагдуулахгүй."""
    return " ".join(str(raw or "").split())


def _key(name: str) -> str:
    return normalize_company(name).lower().rstrip(".:").strip()


def is_junk_company(name) -> bool:
    """Импортын гарчиг / хуудасны нэр мэт БАЙГУУЛЛАГА БИШ утга уу. Хоосон нь хог
    биш (тэр нь «байгууллагагүй» — тусад нь шалгана)."""
    key = _key(name or "")
    if not key:
        return False
    return key in JUNK_COMPANY_NAMES or bool(_NUMBERED_RE.match(key)) or bool(_NO_LETTER_RE.match(key))
