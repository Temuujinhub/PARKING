#!/usr/bin/env bash
# Талбайд хэвлэгдчихсэн QR-тай 3 зогсоолыг системд бүртгэнэ.
#
# Ажиллуулах:  sudo bash /root/PARKING/deploy/setup_new_sites.sh
#
# UUID-ууд нь docs/Зогсоолqr/ доторх зурагнуудын QR кодоос ТАЙЛАГДСАН утгууд —
# гараар бүү өөрчил. Тэмдэг бүрийг дахин хэвлэх боломжгүй тул зогсоолын id нь
# QR доторх UUID-тай ЯГ таарч байж /checkout/<uuid> линк ажиллана.
#
# Скрипт идемпотент — олон удаа ажиллуулж болно.
set -euo pipefail

PY=/root/PARKING/backend/venv/bin/python
ADD=/root/PARKING/tools/add_site.py

BASE=https://app.easy-parking.mn

add() {  # add <uuid> <код> <нэр> <хаяг> <хэвлэгдсэн-QR-линк>
  echo
  echo "──────────────────────────────────────────────────────────────"
  "$PY" "$ADD" --id "$1" --code "$2" --name "$3" --address "$4" --capacity 0 --qr-url "$5"
}

# 5 дахь аргумент = самбар дээр ХЭВЛЭГДСЭН яг тэр линк. Үүнийг өгсний ачаар
# Тохиргоо → QR → "Хэвлэх PNG татах" нь самбартай ЯГ ИЖИЛ QR гаргана.
add 565a3ddb-1c01-4201-ad1c-81fc449cbdd7 SPORT  "Спортын төв ордон" "Спортын төв ордны баруун тал" \
    "$BASE/checkout/565a3ddb-1c01-4201-ad1c-81fc449cbdd7"
add 7c25552b-98bd-4e9b-bc18-a3df6ba8add0 KH     "Кэй Эйч хотхон"    "Кэй Эйч хотхоны баруун тал" \
    "$BASE/check-cost/7c25552b-98bd-4e9b-bc18-a3df6ba8add0"
add b8773f25-2ef7-408e-9abf-cc30961c5716 MONNIS "Моннис билдинг"    "Monnis building" \
    "$BASE/checkout/b8773f25-2ef7-408e-9abf-cc30961c5716"

cat <<'NOTE'

──────────────────────────────────────────────────────────────
Бүртгэл дууслаа. Дараагийн алхмууд (гараар):

  1. Тариф — зогсоол бүрд автоматаар ЭХНИЙ идэвхтэй тариф холбогдсон.
     Тохиргоо → Тариф хэсгээс зогсоол тус бүрийн үнийг шалгаж тохируулна уу.

  2. Багтаамж — бүгд "дүүргэлтгүй" (хязгааргүй) болгосон. Тодорхой тоо
     хэрэгтэй бол Тохиргоо → Зогсоол хэсгээс засна.

  3. Камер / хаалт — эдгээр зогсоолд төхөөрөмж хараахан бүртгээгүй. Тиймээс
     машин орох/гарах бүртгэл автоматаар үүсэхгүй, QR хуудас "нээлттэй
     бүртгэл олдсонгүй" гэж хэлнэ. Камерууд холбогдмогц Тохиргоо →
     Төхөөрөмж хэсгээс нэмнэ.

  4. Моннис — тусдаа төлбөрийн хэрэгсэл (QPay данс) холбох ажил хүлээгдэж
     байна. Одоогоор бүх зогсоол нэг QPay данс руу төлнө.
NOTE
